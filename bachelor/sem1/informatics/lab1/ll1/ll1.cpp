#include <iostream>
#include <iomanip>
using namespace std;
void calcfloat()
{
    setlocale(LC_ALL, "RU");
    float af, bf, cf, df, ef, ff, gf;
    af = 1000;
    bf = 0.0001;
    cf = (af + bf) * (af + bf) * (af + bf); //вычеслим первую часть числителя
    df = (af * af * af) + (3 * (af * af) * bf); //вычеслим вторую часть числителя
    ef = cf - df; //вычеслим чеслитель 
    ff = (3 * af * (bf * bf)) + (bf * bf * bf); //вычеслим знаменатель
    gf = ef / ff; //вычеслим полное выражение
    cout << "float:  числитель = " << ef
        << ", знаменатель = " << ff
        << ", результат = " << gf << endl; // выводим значения числителя, знаменателя и результат выражения
}
void calcdouble()
{
    setlocale(LC_ALL, "RU");
    double a, b, c, d, e, f, g;
    a = 1000;
    b = 0.0001;
    c = (a + b) * (a + b) * (a + b); //вычеслим первую часть числителя
    d = (a * a * a) + (3 * (a * a) * b); //вычеслим вторую часть числителя
    e = c - d;//вычеслим чеслитель
    f = (3 * a * (b * b)) + (b * b * b); //вычеслим знаменатель
    g = e / f; //вычеслим полное выражение
    cout << "double:  числитель = " << e
        << ", знаменатель = " << f
        << ", результат = " << g << endl; // выводим значения числителя, знаменателя и результат выражения
}
void calcmn()
{
    setlocale(LC_ALL, "RU");
    int n, m, r;

    // 1) n---m  разбирается как (n--) - m
    n = 5; m = 3;
    r = n-- - m;      // берётся старое n (5), вычисляется 5 - 3 = 2, затем n уменьшается до 4
    cout << "1) n---m : результат = " << r
        << ", n = " << n << ", m = " << m << endl;   // 2, n=4, m=3

    // 2) m--<n  разбирается как (m--) < n
    n = 5; m = 3;
    r = m-- < n;      // сравнивается старое m (3) с n (5): 3 < 5 даёт 1, затем m уменьшается до 2
    cout << "2) m--<n : результат = " << r
        << ", n = " << n << ", m = " << m << endl;   // 1, n=5, m=2

    // 3) n++>m  разбирается как (n++) > m
    n = 5; m = 3;
    r = n++ > m;      // сравнивается старое n (5) с m (3): 5 > 3 даёт 1, затем n увеличивается до 6
    cout << "3) n++>m : результат = " << r
        << ", n = " << n << ", m = " << m << endl;   // 1, n=6, m=3
}
int main()
{
    setlocale(LC_ALL, "RU");
    cout << fixed << setprecision(10);
    calcfloat();
    calcdouble();
    calcmn();
    return 0;
}
